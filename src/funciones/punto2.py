# Función que verifica si un número es par
def es_par(numero):  
    # Se define la función es_par que recibe un número como parámetro
    return numero % 2 == 0  
# Retorna True si el residuo de dividir el número entre 2 es 0 (es par), de lo contrario False

# Función que convierte temperatura de Celsius a Fahrenheit
def celsius_a_fahrenheit(celsius):  
    # Se define la función celsius_a_fahrenheit que recibe una temperatura en grados Celsius
    return (celsius * 9/5) + 32  
# Retorna el valor convertido a grados Fahrenheit usando la fórmula
