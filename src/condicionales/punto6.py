# Guardamos un número en la variable 'numero'
numero = 15

# Usamos el operador módulo (%) para verificar si el residuo al dividir entre 2 es 0
if numero % 2 == 0:
    # Si el residuo es 0, significa que el número es par
    print("El número es par.")
else:
    # Si no es 0, significa que el número es impar
    print("El número es impar.")