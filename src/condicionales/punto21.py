# Definimos el valor booleano a como True
a = True
# Definimos el valor booleano b como False
b = False
# Definimos c como el valor contrario de b (not b)
c = not b

# Calculamos el resultado de la expresión lógica a or b and c
# Se evalúa 'and' primero, luego 'or'
resultado = a or b and c
# Imprimimos el resultado en pantalla
print(resultado)  # Imprime True
