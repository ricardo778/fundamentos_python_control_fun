# Definimos el número a evaluar
numero = 0

# Verificamos si el número es mayor que cero
if numero > 0:
    # Si es mayor que cero, mostramos que es positivo
    print("El número es positivo.")
# Verificamos si el número es menor que cero
elif numero < 0:
    # Si es menor que cero, mostramos que es negativo
    print("El número es negativo.")
# Si no es mayor ni menor, entonces debe ser cero
else:
    # Mostramos que el número es cero
    print("El número es cero.")