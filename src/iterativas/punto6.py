# Diccionario con información de un usuario
usuario = {"nombre": "Laura", "edad": 28, "ciudad": "Madrid"}   
# Guardo un diccionario con datos de una persona

# Ciclo for para recorrer las claves del diccionario
for clave in usuario:                                           
    # Recorro cada clave dentro del diccionario 'usuario'
    print(f"Clave: {clave}, Valor: {usuario[clave]}")           
    # Imprimo la clave y el valor asociado a esa clave