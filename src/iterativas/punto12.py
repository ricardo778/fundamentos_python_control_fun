contador = 1  
# Empiezo con un contador en 1

while contador <= 5:  
    # Mientras el contador sea menor o igual a 5, el ciclo sigue
    print(f"Iteración número {contador}")  
    # Muestro el número de la vuelta
    contador += 1  
    # Aumento el contador en 1 para que algún momento la condición se vuelva falsa